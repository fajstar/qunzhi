# -*- coding: utf-8 -*-
"""
课题复杂度分级模块 complexity.py
=================================
多维度定级法（通用版：覆盖科研/工程/教研三类场景）

V15.5 修复：原版三类定义（教学技巧/课程设计/制度决策）只适用教研场景，
导致科研难题被误判（如"低温 SOC 估算误差"被判简单）。
新版引入 4 个通用维度，其中"技术成熟度"与"认知复杂度"专治科研/工程问题。
"""
import sys, os

QA_PROMPT = """你是课题复杂度评估专家。请综合以下 4 个维度判断课题复杂度（适用于科研、工程、教研等各类问题）。

【维度1 · 认知复杂度】解决它只需单一领域的一个方法，还是需要多学科/多视角交叉？
  - 低：一个成熟方法就能搞定
  - 高：需要跨领域知识或多种角色视角碰撞（如"电化学+控制理论+AI"）

【维度2 · 方法成熟度】现有主流方法是否已到瓶颈？
  - 低：有成熟方案直接可用
  - 高：提问者已尝试主流方法但效果不佳（如明确说"用了X，只提升Y"），或需换研究范式

【维度3 · 决策层级】
  - 低：个人层面的一个动作/技巧
  - 中：需要设计一套方案/体系
  - 高：涉及制度/政策/伦理/多方利益

【维度4 · 不确定性与权衡】答案是否唯一明确？
  - 低：有标准答案
  - 高：存在权衡、争议、需要预演论证

【分级规则】
- **简单**：四维全低 —— 一个技巧/成熟方法即可解决，答案明确
- **复杂**：任一维度为高，尤其是"方法已到瓶颈需换范式"或"需多学科交叉"
- **中等**：介于两者之间（需设计方案但范围有限，或有一定技术难度但有可行路径）

【关键判别（防止误判）】
1. **不要因为问题表述简短就判为简单**——看问题的本质难度；
2. **科研/工程类问题**：若涉及多子系统耦合、已在主流方法上受挫、或需要实验验证，判为**复杂**；
3. **教育类问题**：单纯的课堂技巧（如何导入/如何提问）→ 简单；设计一门课/一份方案 → 中等；
   但凡涉及**学生学习行为改变、动机激发、评价制度改革、多方利益协调**（学生/教师/家长/学校），
   判为**复杂**——因为这类问题的难点在于人的行为与制度，而非教学方法本身；
4. 典型判例参考：
   - "如何教中学生一次函数" → 简单（成熟教学技巧）
   - "Excel 怎么做数据透视表" → 简单（成熟工具操作）
   - "如何设计一门选修课大纲" → 中等（设计方案，范围有限）
   - "如何优化 MySQL 慢查询" → 中等（有成熟调优路径）
   - "低温下电池SOC估算误差超8%，卡尔曼滤波改进后仅到6%" → **复杂**（方法遇瓶颈+跨学科）
   - "如何提升师范生课堂参与度" → **复杂**（涉及学生动机+教师行为+评价制度）
   - "AI作业该禁止还是引导" → **复杂**（制度决策+多方利益）

【输出】严格 JSON：{{"level": "A/B/C", "reason": "一句话理由（说明哪个维度导致该判定）"}}
课题：{topic}"""


def assess_complexity(topic: str, api_caller=None) -> str:
    """多维度定级（通用：科研/工程/教研），返回 简单/中等/复杂"""
    if not api_caller:
        return "中等"
    try:
        r = api_caller(QA_PROMPT.format(topic=topic), max_tokens=300, temperature=0.1, timeout=25)
        level = "中等"
        if r:
            import re, json as _json
            # 优先解析 JSON 里的 level
            try:
                m = re.search(r'\{[^{}]*"level"[^{}]*\}', r, re.S)
                if m:
                    d = _json.loads(m.group())
                    lv = str(d.get("level", "")).strip().upper()
                    if lv in ("A", "B", "C"):
                        return {"A": "简单", "B": "中等", "C": "复杂"}[lv]
                    if lv in ("简单", "中等", "复杂"):
                        return lv
            except Exception:
                pass
            # 回退：从 "level": "C" 这类模式提取
            m2 = re.search(r'"level"\s*:\s*"([ABC])"', r)
            if m2:
                return {"A": "简单", "B": "中等", "C": "复杂"}[m2.group(1)]
            # 最后回退：整段回复很短时，才认它是一个独立的 A/B/C
            # （原实现用 \b([ABC])\b 全文匹配，会被 "Plan B"/"方案 C" 这类正文误触发）
            stripped = r.strip()
            if len(stripped) <= 24:
                m3 = re.search(r'\b([ABC])\b', stripped)
                if m3:
                    level = {"A": "简单", "B": "中等", "C": "复杂"}[m3.group(1)]
        return level
    except Exception:
        return "中等"


# 复杂度 → 讨论轮数 / 输出形态
LEVEL_CONFIG = {
    "简单": {"max_rounds": 1, "output": "quick"},    # 快速建议，1轮
    "中等": {"max_rounds": 2, "output": "standard"},  # 标准建议书，2轮
    "复杂": {"max_rounds": 3, "output": "full"},      # 完整建议书+盲区+风险，3轮
}


def get_level_config(level: str) -> dict:
    return LEVEL_CONFIG.get(level, LEVEL_CONFIG["中等"])


if __name__ == "__main__":
    print(assess_complexity("如何教中学生一次函数"))
